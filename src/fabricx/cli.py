"""fabricx command line."""
import os
from datetime import datetime, timezone
from pathlib import Path

import typer

from . import collectors, diagram, generate, model, report, runner, validators
from . import drift as driftmod
from . import trace as tracemod

# Same default as model.load(): $FABRICX_INVENTORY, else the main inventory.
INV = Path(os.environ.get("FABRICX_INVENTORY", "inventory/fabric.yaml"))

app = typer.Typer(help="FabricX fabric lab tool", no_args_is_help=True)


@app.callback()
def main() -> None:
    """FabricX."""


@app.command("generate")
def gen(inventory: Path = INV, out: Path = Path("generated"),
        routing: bool = True) -> None:
    """Generate containerlab topology and node configs from the inventory."""
    f = model.load(inventory)
    files = generate.write_all(f, out, routing)
    Path("docs/topology.md").write_text("# Topology (generated)\n\n" + diagram.mermaid(f))
    typer.echo(f"wrote {len(files)} files to {out}/ and docs/topology.md")


@app.command()
def validate(inventory: Path = INV, out: Path = Path("artifacts/validate")) -> None:
    """Collect live state, compare with the inventory's intent, write a report. Exit 1 on findings."""
    f = model.load(inventory)
    run_dir = out / datetime.now(timezone.utc).strftime("%Y-%m-%dT%H-%M-%SZ")
    state = collectors.Collector(f, run_dir).snapshot()
    findings = validators.validate(f, state)
    path = report.write(run_dir, findings, state)
    typer.echo(f"report: {path}")
    for x in findings:
        typer.echo(f"FAIL {x.check} {x.node}: {x.message}")
    typer.echo("PASS" if not findings else f"{len(findings)} findings")
    raise typer.Exit(code=1 if findings else 0)


@app.command()
def deploy(inventory: Path = INV, out: Path = Path("generated")) -> None:
    """Generate, then deploy the lab with Containerlab."""
    gen(inventory, out)
    r = runner.sh(f"containerlab deploy -t {out.resolve()}/{model.load(inventory).name}.clab.yml", timeout=600)
    typer.echo(r.stdout[-400:] + r.stderr[-400:])
    raise typer.Exit(code=r.returncode)


@app.command()
def destroy(inventory: Path = INV, out: Path = Path("generated")) -> None:
    """Destroy the lab."""
    name = model.load(inventory).name
    r = runner.sh(f"containerlab destroy -t {out.resolve()}/{name}.clab.yml --cleanup", timeout=300)
    typer.echo(r.stderr[-300:])
    raise typer.Exit(code=r.returncode)


@app.command()
def drift(inventory: Path = INV) -> None:
    """Compare each switch's running FRR config with what the inventory would generate. Exit 1 on drift."""
    f = model.load(inventory)
    files = generate.render_all(f)
    bad = 0
    for sw in f.spines + f.leaves:
        try:
            r = runner.node_exec(f.name, sw.name, "vtysh -c 'show running-config'", timeout=15, retries=1)
        except runner.NodeUnreachable as exc:
            typer.echo(f"UNREACHABLE {sw.name}: {exc.reason}")
            bad += 1
            continue
        missing, extra = driftmod.diff(files[f"configs/{sw.name}/frr.conf"], r.stdout, nos=sw.nos)
        for m in missing:
            typer.echo(f"DRIFT {sw.name}: missing from running config: {m}")
        for e in extra:
            typer.echo(f"DRIFT {sw.name}: not in inventory: {e}")
        bad += bool(missing or extra)
    typer.echo("no drift" if not bad else f"{bad} node(s) drifted")
    raise typer.Exit(code=1 if bad else 0)


@app.command("report")
def show_report(out: Path = Path("artifacts/validate")) -> None:
    """Print the newest validation report."""
    runs = sorted(out.glob("*/report.md"))
    typer.echo(runs[-1].read_text() if runs else "no reports yet; run `fabricx validate`")


@app.command()
def trace(out: Path = Path("docs/traceability.md")) -> None:
    """Generate the requirement-test-evidence matrix from tests/specs. Exit 1 if a spec names a missing test."""
    specs = tracemod.load_specs()
    md, problems = tracemod.build(specs, tracemod.collected_ids(), tracemod.junit_results())
    out.write_text("# Traceability matrix (generated by `fabricx trace`)\n\n" + md)
    for p in problems:
        typer.echo(f"PROBLEM {p}")
    typer.echo(f"{len(specs)} requirements -> {out}")
    raise typer.Exit(code=1 if problems else 0)


