@app.command()
def inject(fault_id: str, inventory: Path = INV) -> None:
    """Inject a fault (lab containers only). Remember it with `fabricx restore`."""
    from .faults import get
    from .faults import runner as fr
    f = model.load(inventory)
    fr.inject(f, get(fault_id))
    typer.echo(f"injected {fault_id.upper()}; restore with `fabricx restore`")


@app.command()
def restore(inventory: Path = INV) -> None:
    """Undo the active fault."""
    import json as _json

    from .faults import get
    from .faults import runner as fr
    if not fr.ACTIVE.exists():
        typer.echo("no active fault")
        raise typer.Exit(code=0)
    fid = _json.loads(fr.ACTIVE.read_text())["id"]
    fr.restore(model.load(inventory), get(fid))
    typer.echo(f"restored {fid}")


@app.command()
def diagnose(inventory: Path = INV) -> None:
    """Layered, bottom-up diagnosis from live state. Exit 1 if a problem is found."""
    from . import diagnose as dg
    d, _ = dg.diagnose(model.load(inventory))
    typer.echo(dg.render(d))
    raise typer.Exit(code=0 if d.healthy else 1)


@app.command("run-fault")
def run_fault_cmd(fault_id: str, probe_seconds: int = 0, inventory: Path = INV) -> None:
    """Full fault run with evidence bundle: baseline, inject, observe, diagnose, restore, re-check."""
    import json as _json

    from .faults import get
    from .faults import runner as fr
    res = fr.run_fault(model.load(inventory), get(fault_id), probe_seconds=probe_seconds)
    typer.echo(_json.dumps(res, indent=1))


@app.command()
def drill(seed: int = 1, out: Path = Path("experiments/E9/results"), only: str = "",
          inventory: Path = INV) -> None:
    """Blind drill: inject every catalogue fault in a random (seeded) order; diagnose never sees which one."""
    import json as _json
    import random

    from .faults import CATALOGUE
    from .faults import runner as fr
    f = model.load(inventory)
    order = [x for x in CATALOGUE if not only or x.id in only.split(",")]
    random.Random(seed).shuffle(order)
    out.mkdir(parents=True, exist_ok=True)
    results = []
    for fault in order:
        try:
            res = fr.run_fault(f, fault)
        except Exception as exc:  # noqa: BLE001
            fr.restore(f, fault)
            res = {"fault": fault.id, "localised": False, "error": repr(exc)}
        results.append(res)
        typer.echo(f"{fault.id}: localised={res['localised']} causes={res.get('diagnosed_causes')}")
    ok = sum(bool(r["localised"]) for r in results)
    (out / f"drill_seed{seed}.json").write_text(_json.dumps({"seed": seed, "localised": ok, "total": len(results),
                                                             "results": results}, indent=1))
    typer.echo(f"localised {ok}/{len(results)}")


