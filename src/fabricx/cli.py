@app.command("audit-qos")
def audit_qos(config_db: Path) -> None:
    """Audit a SONiC config_db.json (PFC/ECN/DSCP consistency). Exit code 1 if any error finding."""
    import json

    from .audit import qos_lossless
    findings = qos_lossless.audit(json.loads(config_db.read_text()))
    typer.echo(qos_lossless.render(findings))
    if any(x.severity == "error" for x in findings):
        raise typer.Exit(1)


