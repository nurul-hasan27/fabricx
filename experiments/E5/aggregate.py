"""Builds experiments/E5/results.md from the raw runs of E1 (eBGP) and E5 (OSPF, IS-IS)."""
import gzip
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, "src")
from fabricx import generate, model  # noqa: E402


def duration(d: str) -> float:
    return 75.0 if "nobfd_gray" in d and "E5" in d else 16.0 if "E1/results/nobfd_gray" in d else 8.0


def outage_ms(p: Path, dur: float) -> float:
    """Longest gap, including a trailing gap if the outage was still going when the sender stopped (see E1 analysis)."""
    r = json.loads((p / "result.json").read_text())
    rows = sorted((tuple(int(x) for x in ln.split(",")) for ln in
                   gzip.open(p / "probe.csv.gz", "rt").read().splitlines()[1:]), key=lambda x: x[2])
    gaps = [b[2] - a[2] for a, b in zip(rows, rows[1:], strict=False)]
    longest = max(gaps, default=0) / 1e6
    trailing = max(0, r["inject_ts_ns"] + int((dur - 3.0) * 1e9) - rows[-1][2]) / 1e6
    return max(longest, trailing) if trailing > max(longest, 1000) else longest


def row(label, d):
    dirs = sorted(Path(d).glob("run*"))
    if not dirs:
        return None
    rs = dirs
    allg = [outage_ms(p, duration(d)) for p in rs]
    hit = [g for g in allg if g >= 100]
    med_hit = f"{statistics.median(hit):.0f}" if hit else "-"
    rng = f"{min(hit):.0f} to {max(hit):.0f}" if hit else "-"
    return f"| {label} | {len(rs)} | {len(hit)} | {med_hit} | {rng} | {statistics.median(allg):.0f} |"


cells = [("eBGP (E1), carrier loss, BFD", "experiments/E1/results/bfd_carrier"),
         ("OSPF, carrier loss, BFD", "experiments/E5/results/ospf-bfd_carrier"),
         ("IS-IS, carrier loss, BFD", "experiments/E5/results/isis-bfd_carrier"),
         ("eBGP (E1), gray failure, BFD", "experiments/E1/results/bfd_gray"),
         ("OSPF, gray failure, BFD", "experiments/E5/results/ospf-bfd_gray"),
         ("IS-IS, gray failure, BFD", "experiments/E5/results/isis-bfd_gray"),
         ("eBGP (E1), gray, no BFD, hold 9 s", "experiments/E1/results/nobfd_gray"),
         ("OSPF, gray, no BFD, dead 40 s", "experiments/E5/results/ospf-nobfd_gray"),
         ("IS-IS, gray, no BFD, hold 40 s", "experiments/E5/results/isis-nobfd_gray")]
out = ["# E5 results (generated by aggregate.py from raw runs)", "",
       "Outage = longest gap between received 1 ms probes (h1 -> h3). 'Runs with impact' = runs with at least 100 ms outage or 100 lost "
       "packets; the other runs did not hit the probe flow (or stayed below the noise floor) and are excluded from the range but "
       "included in the all-runs median.", "",
       "| Underlay / fault / detection | Runs | Runs with impact | Median outage, impacted runs (ms) | Range (ms) | Median, all runs (ms) |",
       "|---|---|---|---|---|---|"]
out += [r for r in (row(a, b) for a, b in cells) if r]
out += ["", "## Configuration size (leaf1 `frr.conf`, non-comment lines, from the same inventory)", "", "| Underlay | Lines |", "|---|---|"]
for name, inv in (("eBGP", "inventory/fabric.yaml"), ("OSPF + iBGP RR", "inventory/variants/ospf.yaml"),
                  ("IS-IS + iBGP RR", "inventory/variants/isis.yaml")):
    txt = generate.render_all(model.load(inv))["configs/leaf1/frr.conf"]
    n = sum(1 for ln in txt.splitlines() if ln.strip() and not ln.strip().startswith("!"))
    out.append(f"| {name} | {n} |")
Path("experiments/E5/results.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
