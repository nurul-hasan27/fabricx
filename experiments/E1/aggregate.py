"""Build experiments/E1/results.md from the stored raw probe CSVs (no numbers typed by hand).

Outage = the longest gap between received probes. A fault that is NOT repaired before the sender
stops leaves a *trailing* gap that the plain 'longest gap' misses (found with the 200 s runs), so
the trailing gap (sender end - last arrival) is included and such runs are flagged as censored
(true outage >= reported value).
"""
import gzip
import json
import statistics
from pathlib import Path

base = Path("experiments/E1/results")
DUR = {"bfd_carrier": 8, "bfd_gray": 8, "nobfd_carrier": 8, "nobfd_gray": 16, "default_gray": 200}
INJECT_AT = 3.0
names = {"bfd": "BGP 3/9 s + BFD 300 ms x3", "nobfd": "BGP 3/9 s, no BFD", "default": "BGP defaults 60/180 s, no BFD"}


def outage(run_dir: Path, duration: float):
    r = json.loads((run_dir / "result.json").read_text())
    rows = sorted((tuple(int(x) for x in ln.split(",")) for ln in
                   gzip.open(run_dir / "probe.csv.gz", "rt").read().splitlines()[1:]), key=lambda x: x[2])
    gaps = [b[2] - a[2] for a, b in zip(rows, rows[1:])]
    longest = max(gaps, default=0) / 1e6
    end_ts = r["inject_ts_ns"] + int((duration - INJECT_AT) * 1e9)
    trailing = max(0, end_ts - rows[-1][2]) / 1e6
    # an arrival-free tail longer than the in-run gaps (and > 1 s) = fault never repaired during the run
    cens = trailing > max(longest, 1000)
    return max(longest, trailing) if cens else longest, cens, r["lost"]


rows = ["| Profile | Fault | N | Outage min (ms) | median (ms) | max (ms) | Not recovered in run | Lost pkts median |",
        "|---|---|---|---|---|---|---|---|"]
detail = []
for cell, dur in DUR.items():
    runs = [outage(p.parent, dur) for p in sorted((base / cell).glob("run*/result.json"))]
    if not runs:
        continue
    g = [x[0] for x in runs]
    prof, fault = cell.split("_")
    rows.append(f"| {names[prof]} | {fault} | {len(g)} | {min(g):.1f} | {statistics.median(g):.1f} | {max(g):.1f} | "
                f"{sum(x[1] for x in runs)} | {statistics.median(x[2] for x in runs):.0f} |")
    detail.append(f"- `{cell}` per-run outage (ms{', * = unrecovered, true value higher' if any(x[1] for x in runs) else ''}): "
                  + ", ".join(f"{x[0]:.0f}{'*' if x[1] else ''}" for x in runs))
out = ["# E1 results (generated by aggregate.py from raw runs)", "",
       "Probe: 1 ms interval, h1 -> h3. Noise floor about 3-9 ms (see method.md). Faults injected on the leaf1 uplink the probe flow uses.", ""] + rows + [""] + detail + [""]
Path("experiments/E1/results.md").write_text("\n".join(out))
print("\n".join(out))
