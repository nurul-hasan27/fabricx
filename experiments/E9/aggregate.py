"""Builds experiments/E9/results.md (blind drill) and experiments/E4/symptoms.md from the stored drill JSON files."""
import json
from pathlib import Path

files = sorted(Path("experiments/E9/results").glob("drill_seed*.json"))
runs = [json.loads(p.read_text()) for p in files]
out = ["# E9 — blind drill (generated by aggregate.py)", "",
       "`fabricx drill` injects each catalogue fault in a seeded random order; `fabricx diagnose` sees only live state and the inventory.",
       "A fault counts as localised when the primary diagnosis reports the fault's cause key in the fault's layer.", ""]
for d in runs:
    out.append(f"- seed {d['seed']}: **{d['localised']}/{d['total']} localised**")
out += [""]
for d in runs:
    out += [f"## Seed {d['seed']}", "", "| Fault | Layer | Expected cause | Diagnosed | Localised | Recovery (s) |", "|---|---|---|---|---|---|"]
    for r in sorted(d["results"], key=lambda x: x["fault"]):
        out.append(f"| {r['fault']} {r.get('name', '')} | {r.get('layer', '')} | {r.get('expected_cause', '')} | "
                   f"{', '.join(r.get('diagnosed_causes', [])) or '-'} | {'yes' if r['localised'] else '**NO**'} | "
                   f"{r.get('timeline', {}).get('recovery_s', 0):.0f} |")
    out.append("")
Path("experiments/E9/results.md").write_text("\n".join(out) + "\n")

last = {}
for d in runs:
    for r in d["results"]:
        last[r["fault"]] = r
rows = ["# E4 / catalogue — what each fault looks like to the customer (generated)", "",
        "c1 = same subnet across leaves (h1>h3), c2 = local routing (h1>h2), c3 = routed across leaves (h1>h4), "
        "c4 = RED to BLUE isolation (breach = reachable).", "",
        "| Fault | c1 | c2 | c3 | Isolation breached | Hypothesis matched | First evidence |", "|---|---|---|---|---|---|---|"]
from fabricx.faults import CATALOGUE  # noqa: E402

for fl in CATALOGUE:
    r = last.get(fl.id)
    if not r:
        continue
    bad = set(r.get("observed_failing", []))
    c1, c2, c3 = ("FAIL" if c in bad else "ok" for c in ("c1", "c2", "c3"))
    rows.append(f"| {fl.id} {fl.name} | {c1} | {c2} | {c3} | {r.get('isolation_breach')} | "
                f"{r.get('symptoms_match_hypothesis')} | {fl.first_evidence} |")
Path("experiments/E4/symptoms.md").write_text("\n".join(rows) + "\n")
print("\n".join(out[:6]))
